"""Render pipeline: named steps, codegen, execution, per-step verification."""

from __future__ import annotations

import json
import shlex
import sys
import time
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any

from vedit.errors import RenderError
from vedit.media import CommandResult, probe, resolve_ffmpeg, run_command, shell_join
from vedit.otio import write_otio


@dataclass
class Step:
    name: str
    argv: list[str]
    outputs: list[str]
    description: str
    optional: bool = False

    def as_dict(self) -> dict[str, Any]:
        return {
            "name": self.name,
            "argv": self.argv,
            "outputs": self.outputs,
            "description": self.description,
            "optional": self.optional,
            "shell": shell_join(self.argv),
        }


@dataclass
class StepReport:
    name: str
    ok: bool
    duration_ms: int
    outputs: list[str]
    stderr_tail: str = ""


@dataclass
class Pipeline:
    name: str
    work_dir: Path
    steps: list[Step] = field(default_factory=list)
    meta: dict[str, Any] = field(default_factory=dict)

    def add(self, step: Step) -> Step:
        self.steps.append(step)
        return step

    def as_dict(self) -> dict[str, Any]:
        return {
            "name": self.name,
            "work_dir": str(self.work_dir),
            "steps": [s.as_dict() for s in self.steps],
            "meta": self.meta,
        }


def _shell_step(argv: list[str]) -> str:
    """Bake portable python -m vedit.* invocations into render.sh."""
    if len(argv) >= 3 and argv[1] == "-m" and str(argv[2]).startswith("vedit"):
        return 'PYTHON="${PYTHON:-python3}"\n$PYTHON ' + shell_join(argv[1:])
    return shell_join(argv)


def load_pipeline(work_dir: str | Path) -> Pipeline:
    root = Path(work_dir).expanduser().resolve()
    project = root / "project.json"
    if not project.is_file():
        raise RenderError(f"no project.json in {root} — run `vedit plan` first")
    data = json.loads(project.read_text(encoding="utf-8"))
    pipe = Pipeline(
        name=str(data.get("name") or root.name),
        work_dir=root,
        meta=data.get("meta") if isinstance(data.get("meta"), dict) else {},
    )
    for raw in data.get("steps") or []:
        pipe.add(
            Step(
                name=str(raw.get("name") or "step"),
                argv=[str(a) for a in (raw.get("argv") or [])],
                outputs=[str(o) for o in (raw.get("outputs") or [])],
                description=str(raw.get("description") or ""),
            )
        )
    return pipe


def write_codegen(pipeline: Pipeline) -> dict[str, Path]:
    """Write inspectable artifacts: project.json, render.sh, per-step scripts."""
    pipeline.work_dir.mkdir(parents=True, exist_ok=True)
    steps_dir = pipeline.work_dir / "steps"
    steps_dir.mkdir(exist_ok=True)
    project_json = pipeline.work_dir / "project.json"
    project_json.write_text(json.dumps(pipeline.as_dict(), indent=2) + "\n", encoding="utf-8")
    sh_lines = [
        "#!/usr/bin/env bash",
        "set -euo pipefail",
        f"# Generated by vedit — {pipeline.name}",
        f"cd {shlex.quote(str(pipeline.work_dir))}",
        "",
    ]
    for i, step in enumerate(pipeline.steps, start=1):
        script = steps_dir / f"{i:02d}_{step.name}.sh"
        body = "#!/usr/bin/env bash\nset -euo pipefail\n" + _shell_step(step.argv) + "\n"
        script.write_text(body, encoding="utf-8")
        script.chmod(0o755)
        sh_lines.append(f"echo '==> {i:02d} {step.name}: {step.description}'")
        sh_lines.append(_shell_step(step.argv))
        sh_lines.append("")
    render_sh = pipeline.work_dir / "render.sh"
    render_sh.write_text("\n".join(sh_lines), encoding="utf-8")
    render_sh.chmod(0o755)
    otio = write_otio(
        dest=pipeline.work_dir / "timeline.otio.json",
        name=pipeline.name,
        work_dir=str(pipeline.work_dir),
        steps=[s.name for s in pipeline.steps],
        meta=pipeline.meta,
    )
    return {"project": project_json, "render": render_sh, "steps_dir": steps_dir, "otio": otio}


def execute(
    pipeline: Pipeline,
    *,
    dry_run: bool = False,
    resume: bool = False,
    progress: bool = True,
) -> list[StepReport]:
    reports: list[StepReport] = []
    write_codegen(pipeline)
    if dry_run:
        return [
            StepReport(name=s.name, ok=True, duration_ms=0, outputs=s.outputs)
            for s in pipeline.steps
        ]
    total = len(pipeline.steps)
    for index, step in enumerate(pipeline.steps, start=1):
        if progress:
            print(f"==> [{index}/{total}] {step.name}: {step.description}", file=sys.stderr, flush=True)
        if resume and step.outputs and all(Path(p).is_file() for p in step.outputs):
            reports.append(
                StepReport(
                    name=step.name,
                    ok=True,
                    duration_ms=0,
                    outputs=step.outputs,
                    stderr_tail="skipped (outputs exist)",
                )
            )
            if progress:
                print("    skipped (outputs exist)", file=sys.stderr, flush=True)
            continue
        started = time.perf_counter()
        result: CommandResult = run_command(step.argv, stream_stderr=progress)
        elapsed = int((time.perf_counter() - started) * 1000)
        missing = [p for p in step.outputs if not Path(p).exists()]
        ok = result.ok and not missing
        report = StepReport(
            name=step.name,
            ok=ok,
            duration_ms=elapsed,
            outputs=step.outputs,
            stderr_tail="\n".join(result.stderr.strip().splitlines()[-8:]),
        )
        reports.append(report)
        if progress:
            mark = "ok" if ok else "FAIL"
            print(f"    {mark} {elapsed}ms", file=sys.stderr, flush=True)
        if not ok and not step.optional:
            raise RenderError(
                f"step '{step.name}' failed (exit {result.returncode}).\n"
                f"command: {shell_join(step.argv)}\n"
                f"{report.stderr_tail}"
                + (f"\nmissing outputs: {missing}" if missing else "")
            )
    return reports


def write_report(
    pipeline: Pipeline,
    step_reports: list[StepReport],
    *,
    finals: list[Path],
) -> Path:
    payload: dict[str, Any] = {
        "name": pipeline.name,
        "ffmpeg": resolve_ffmpeg(),
        "work_dir": str(pipeline.work_dir),
        "steps": [asdict(r) for r in step_reports],
        "outputs": [],
    }
    for path in finals:
        if not path.is_file():
            payload["outputs"].append({"path": str(path), "exists": False})
            continue
        info = probe(path)
        payload["outputs"].append(
            {
                "path": str(path),
                "exists": True,
                "duration": info.duration,
                "width": info.width,
                "height": info.height,
                "fps": info.fps,
                "has_audio": info.has_audio,
                "has_video": info.has_video,
                "size_bytes": info.size_bytes,
                "format": info.format_name,
            }
        )
    dest = pipeline.work_dir / "report.json"
    dest.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    return dest
